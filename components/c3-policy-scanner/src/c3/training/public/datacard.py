"""Write the data card: exactly which public sources C3 trained on, under what licence, and how
much of the training data is real, machine-generated, or checked by a person.

    python -m c3.training.public.datacard
"""
from __future__ import annotations

import json

from c3.config import COMPONENT_ROOT

MANIFEST = COMPONENT_ROOT / "data" / "public_sources.json"
OUT = COMPONENT_ROOT.parents[1] / "docs" / "reports" / "progress" / "c3" / "data-sources.md"


def _prov() -> dict | None:
    """Provenance of the last real run (copy it to results/ after a Colab run). Smoke runs in
    var/ are never reported."""
    f = COMPONENT_ROOT / "results" / "data_provenance.json"
    return json.loads(f.read_text()) if f.exists() else None


def build() -> str:
    m = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {"sources": []}
    prov = _prov()
    lines = [
        "# C3 data sources",
        "",
        "Which public data C3 uses, under what licence, and what is real or machine-generated.",
        "Rebuild everything with `python -m c3.training.public.fetch` (URLs, licences and SHA-256 "
        "hashes are recorded in `components/c3-policy-scanner/data/public_sources.json`).",
        "",
        "## The short version",
        "",
        "- **Policies are real.** US health-privacy law, a Sri Lankan Act and an FDA guidance document. "
        "Nothing about the policy side is invented.",
        "- **Answers come from three places:** real NIH medical answers, real LLM responses that people "
        "or an LLM jury labelled, and answers an open LLM writes for the real clauses.",
        "- **The machine-written part is the only synthetic part.** There is no public dataset of "
        "\"clinical AI policy clause + AI answer + violation label\", so it has to be produced. Each "
        "generated answer is kept only if a judge agrees with its intended label, and a person can "
        "review the sheet (`review.py`). The hand-written rule bank is no longer used for training.",
        "",
        "## Sources",
        "",
        "| Source | Kind | Licence | Used for | Real? |",
        "|---|---|---|---|---|",
    ]
    for s in m["sources"]:
        if "failed" in s:
            lines.append(f"| {s['title']} | | **download failed** | | |")
            continue
        real = "real" if s.get("real", True) else "machine-generated by its authors"
        lines.append(f"| [{s['title']}]({s['url'] if s['url'].startswith('http') else '#'}) "
                     f"| {s['kind'].replace('_', ' ')} | {s['licence']} | {s['role']} | {real} |")
    lines += [
        "",
        "Not downloaded: the WHO AI-for-health guidance (blocked by a bot check), GDPR and the EU AI Act "
        "(EUR-Lex returns a challenge page). They can be added by hand as Markdown or PDF.",
        "",
        "## How the policy side is split",
        "",
        "| Role | Organisation | Documents |",
        "|---|---|---|",
        "| train | pub-train | HIPAA Privacy Rule, HIPAA Breach Rule, 42 CFR Part 2 |",
        "| validation | pub-val | 45 CFR Part 92 (includes AI decision support tools) |",
        "| held-out test | pub-test | Sri Lanka PDPA 2022, FDA CDS guidance (different country and style) |",
        "| general conduct | pub-conduct | nine short rules written for the Aegis safety categories |",
        "",
        "Held-out means whole documents. No clause of a validation or test document appears in any "
        "training row, and the run fails if one does.",
        "",
    ]
    if prov:
        lines += ["## What the last run trained on", "", "| Source | Items |", "|---|---|"]
        for k, v in sorted(prov["by_source"].items()):
            lines.append(f"| {k} | {v} |")
        lines += [
            "",
            f"- Real text: **{prov['share_real']:.0%}**",
            f"- Machine-generated: **{prov['share_llm_generated']:.0%}**",
            f"- Machine-generated and checked by a person: "
            f"**{prov.get('share_llm_generated_and_human_checked', 0):.0%}**",
            f"- Hand-written templates: **{prov['share_handwritten_templates']:.0%}**",
            "",
        ]
    else:
        lines += ["## What the last run trained on", "", "No public-data run has been recorded yet.", ""]
    lines += [
        "## Honest limits",
        "",
        "- Generated answers are written by a language model told to break or follow a clause. Their "
        "labels are right by construction and filtered by a judge, but they are still machine text.",
        "- Aegis responses are general chat safety data, not clinical. They teach the model to read a "
        "rule and cite it, and they supply real labels, but they are not hospital-specific.",
        "- Legal text is not written for AI assistants, so some clauses are hard to break in an answer.",
        "- Everything here still needs real answers from the protected LLM, labelled by people, "
        "before any research claim (blueprint 8.4).",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
