BY_KEY = {s.key: s for s in SOURCES}


def _sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _hf_url(spec: str) -> str:
    """hf://owner/name[/path/in/repo] -> a resolve URL. Dataset-level specs use the parquet branch."""
    rest = spec[len("hf://"):]
    owner, name, *path = rest.split("/")
    repo = f"{owner}/{name}"
    if path:
        return f"https://huggingface.co/datasets/{repo}/resolve/main/{'/'.join(path)}"
    return f"https://huggingface.co/api/datasets/{repo}/parquet/default/train/0.parquet"


def download(src: Source, force: bool = False, log=print) -> Path:
    RAW.mkdir(parents=True, exist_ok=True)
    out = RAW / src.filename
    if out.exists() and not force:
        return out
    url = _hf_url(src.url) if src.url.startswith("hf://") else src.url
    with httpx.stream("GET", url, headers=UA, timeout=120, follow_redirects=True) as r:
        r.raise_for_status()
        with out.open("wb") as fh:
            for chunk in r.iter_bytes(1 << 20):
                fh.write(chunk)
    log(f"[fetch] {src.key}: {out.stat().st_size // 1024} KB")
    return out


def fetch_all(keys: list[str] | None = None, force: bool = False, log=print,
              with_optional: bool = False) -> dict:
    rows = []
    for src in SOURCES:
        if keys and src.key not in keys:
            continue
        if src.optional and not (with_optional or (keys and src.key in keys)):
            continue
        try:
            path = download(src, force, log)
            rows.append({
                "key": src.key, "kind": src.kind, "title": src.title, "url": src.url,
                "licence": src.licence, "role": src.role, "real": src.real, "optional": src.optional,
                "file": f"data/raw/{src.filename}", "bytes": path.stat().st_size,
                "sha256": _sha(path), "retrieved": time.strftime("%Y-%m-%d"),
            })
        except Exception as exc:  # keep going: one blocked site must not stop the rest
            log(f"[fetch] {src.key} FAILED: {type(exc).__name__}: {str(exc)[:100]}")
            rows.append({"key": src.key, "title": src.title, "url": src.url, "failed": str(exc)[:200]})
    manifest = {"ecfr_snapshot_date": ECFR_DATE, "sources": rows}
    MANIFEST.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--with-optional", action="store_true", help="also fetch the 500 MB DynaBench train set")
    a = ap.parse_args()
    fetch_all(a.only, a.force, with_optional=a.with_optional)


if __name__ == "__main__":
    main()
