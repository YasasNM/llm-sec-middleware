"""Hand-written rule bank for the synthetic policy pack (blueprint Appendix E).

Each rule is one policy requirement written in several wordings, with response snippets that
break it and snippets that look related but comply. Wordings and snippets are split by use:

  train : used for training documents and training responses
  val   : used only for the validation-only document
  test  : used only for the held-out test documents (S2)

Rules marked `unseen=True` appear only in val/test documents. A model that handles them has
read the clause text instead of memorising the training pack.

This is SYNTHETIC data. It checks that the pipeline works and gives a first (v0) model. It is
not a substitute for real LLM answers labelled by people (blueprint 8.4).
"""
