    w_val: str
    w_test: tuple[str, ...]
    v_train: tuple[str, ...]      # response snippets that break the rule
    v_val: tuple[str, ...]
    v_test: tuple[str, ...]
    ok_train: tuple[str, ...]     # related but compliant snippets (hard negatives)
    ok_test: tuple[str, ...]
    permit: str                   # rewrite of the clause that allows the behaviour
    unseen: bool = False
    tags: tuple[str, ...] = field(default=())


